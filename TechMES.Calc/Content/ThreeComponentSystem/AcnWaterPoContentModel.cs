    public static IReadOnlyDictionary<string, double> CalculatePercent(float temperature, float pressureBarAbsolute, int configurationCode)
    {
        double[] pressureList;
        CoefSet[] coefList;
        (float Min, float Max)[] minMaxList;
        double acnContentPercent;

        switch (configurationCode / 10)
        {
            case 1:
                pressureList = PressureList758089;
                coefList = CoefList75;
                minMaxList = MinMax75;
                acnContentPercent = 75.0;
                break;

            case 2:
                pressureList = PressureList758089;
                coefList = CoefList80;
                minMaxList = MinMax80;
                acnContentPercent = 80.0;
                break;

            case 3:
                pressureList = PressureList758089;
                coefList = CoefList89;
                minMaxList = MinMax89;
                acnContentPercent = 89.0;
                break;

            default:
                pressureList = PressureList00;
                coefList = CoefList00;
                minMaxList = MinMax00;
                acnContentPercent = 0.0;
                break;
        }

        var numOfRange = GetNumOfFormula(pressureList, pressureBarAbsolute, out double deviation);

        // В исходном ContentCalc температурные границы применяются только если младший разряд configurationCode равен 0.
        // Legacy имел ошибку при pressure выше последней реперной точки: numOfRange == pressureList.Length, после чего происходил выход за границы minMaxList.
        if (configurationCode % 10 == 0)
        {
            if (numOfRange >= minMaxList.Length)
                throw new CalculationException("content.pressure.out-of-range", $"ACN-Water-PO temperature-limited correlation cannot evaluate pressure {pressureBarAbsolute} bar(abs) above the highest pressure anchor {pressureList[^1]} bar(abs).");

            if (temperature < minMaxList[numOfRange].Min)
                temperature = minMaxList[numOfRange].Min;

            if (temperature > minMaxList[numOfRange].Max)
                temperature = minMaxList[numOfRange].Max;
        }

        double content;

        // Давление ниже минимальной реперной точки.
        if (numOfRange == 0)
        {
            var y1 = GetPolynomValue(temperature, coefList[0]);
            var y2 = GetPolynomValue(temperature, coefList[1]);

            content = y1 + (y1 - y2) * (pressureList[0] - pressureBarAbsolute) / (pressureList[1] - pressureList[0]);
        }
        // Давление выше максимальной реперной точки.
        else if (numOfRange == pressureList.Length)
        {
            content = GetPolynomValue(temperature, coefList[^1]);
        }
        // Практически попали в реперную точку.
        else if (1 - deviation < 0.1)
        {
            content = GetPolynomValue(temperature, coefList[numOfRange]);
        }
        // Интерполяция между соседними полиномами.
        else
        {
            var tmpCount1 = GetPolynomValue(temperature, coefList[numOfRange - 1]);
            var tmpCount2 = GetPolynomValue(temperature, coefList[numOfRange]);

            // Именно такая ориентация интерполяции была в legacy.
            content = tmpCount2 + (tmpCount1 - tmpCount2) * deviation;
        }

        // Сначала рассчитывается PO.
        var poPercent = configurationCode % 10 == 1
            ? content * 100.0
            : Math.Max(0.0, Math.Min(100.0, content * 100.0));

        // Остаток смеси делится между ACN и Water.
        var acnPercent = (100.0 - poPercent) * acnContentPercent * 0.01;
        var waterPercent = 100.0 - poPercent - acnPercent;

        return new Dictionary<string, double>(StringComparer.OrdinalIgnoreCase)
        {
            ["ACN"] = acnPercent,
            ["Water"] = waterPercent,
            ["PO"] = poPercent
        };
    }
