    private static PidTuneIssueContent Create(
        string title,
        string explanation,
        string recommendation,
        string diagramCaption,
        params string[] checklist)
    {
        return new PidTuneIssueContent(
            title,
            explanation,
            recommendation,
            diagramCaption,
            checklist);
    }

    private static string FormatPercent(
        double value)
    {
        return (value * 100).ToString("0.##") + " %";
    }
