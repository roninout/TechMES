namespace TechMES.Web.Components.Common;

/// <summary>
/// Определяет способ отображения серий в универсальном ECharts-компоненте трендов.
/// Компонент, масштабирование, touch-навигация, tooltip и загрузка истории остаются общими;
/// меняется только визуальное представление линии.
/// </summary>
public enum EquipmentTrendRenderStyle
{
    /// <summary>
    /// Линия с полупрозрачной заливкой области под ней. Используется на вкладке Graph.
    /// </summary>
    Area,

    /// <summary>
    /// Обычная линия без заливки. Используется на вкладке Tune и может применяться
    /// будущими страницами, которым нужно одновременно показать несколько трендов.
    /// </summary>
    Line
}
